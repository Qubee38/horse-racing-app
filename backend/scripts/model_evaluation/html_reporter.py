    def _build_threshold_based_section(self, results: Dict[str, StrategyResult]) -> str:
        """確率閾値ベース戦略セクションを構築"""
        html = """
        <section id="threshold-based" class="section">
            <h2>3. 確率閾値ベース戦略</h2>
            <p>予測確率が一定閾値以上の馬に投資する戦略</p>
        """
        
        # 単勝
        html += "<h3>単勝</h3>"
        html += self._build_threshold_table(results, 'win')
        
        # 複勝
        html += "<h3>複勝</h3>"
        html += self._build_threshold_table(results, 'place')
        
        html += "</section>"
        return html
    
    def _build_threshold_table(self, results: Dict[str, StrategyResult], bet_type: str) -> str:
        """閾値ベース戦略のテーブルを構築"""
        html = """
        <table>
            <thead>
                <tr>
                    <th>モデル</th>
                    <th>閾値</th>
                    <th>レース数</th>
                    <th>推奨馬数</th>
                    <th>的中馬数</th>
                    <th>的中率</th>
                    <th>投資額</th>
                    <th>払戻額</th>
                    <th>収支</th>
                    <th>ROI</th>
                </tr>
            </thead>
            <tbody>
        """
        
        # 最高ROIを見つける
        threshold_results = {k: v for k, v in results.items() if f'_{bet_type}' in k and 'threshold' in k}
        best_roi = max([r.roi for r in threshold_results.values()]) if threshold_results else 0
        
        for model_type in ['win_model', 'place_model']:
            thresholds = self.config.PROBABILITY_THRESHOLDS[bet_type][model_type]
            
            for threshold in thresholds:
                strategy_name = f"threshold_{model_type}_{int(threshold)}_{bet_type}"
                
                if strategy_name in results:
                    result = results[strategy_name]
                    roi_class = 'roi-positive' if result.roi >= 100 else 'roi-negative'
                    is_best = 'best-strategy' if result.roi == best_roi and result.roi > 0 else ''
                    
                    html += f"""
                    <tr class="{is_best}">
                        <td>{model_type.replace('_', ' ').title()}</td>
                        <td>{int(threshold)}%</td>
                        <td>{result.total_races}</td>
                        <td>{result.total_horses}</td>
                        <td>{result.hit_horses}</td>
                        <td>{result.accuracy:.2f}%</td>
                        <td>{result.total_investment:,}円</td>
                        <td>{result.total_payout:,}円</td>
                        <td class="{roi_class}">{result.profit:+,}円</td>
                        <td class="{roi_class}">{result.roi:.2f}%</td>
                    </tr>
                    """
        
        html += """
            </tbody>
        </table>
        """
        
        return html
    
    def _build_conditional_sections(
        self,
        venue_results: Optional[Dict],
        grade_results: Optional[Dict],
        track_results: Optional[Dict],
        distance_results: Optional[Dict],
        condition_results: Optional[Dict]
    ) -> str:
        """条件別分析セクションを構築"""
        html = ""
        
        if venue_results:
            html += self._build_conditional_section('venue', '競馬場別分析', venue_results)
        
        if grade_results:
            html += self._build_conditional_section('grade', 'グレード別分析', grade_results)
        
        if track_results:
            html += self._build_conditional_section('track-type', 'トラック別分析', track_results)
        
        if distance_results:
            html += self._build_conditional_section('distance', '距離別分析', distance_results)
        
        if condition_results:
            html += self._build_conditional_section('condition', '馬場状態別分析', condition_results)
        
        return html
    
    def _build_conditional_section(
        self,
        section_id: str,
        section_title: str,
        conditional_results: Dict[str, Dict[str, StrategyResult]]
    ) -> str:
        """条件別分析の個別セクションを構築"""
        html = f"""
        <section id="{section_id}" class="section">
            <h2>{section_title}</h2>
            <div class="conditional-grid">
        """
        
        for condition_value, strategies in conditional_results.items():
            # 最高ROIの戦略を見つける
            best_strategy = max(strategies.items(), key=lambda x: x[1].roi)
            best_name, best_result = best_strategy
            
            # 予想順位ベースの結果を取得
            rank_win = strategies.get('rank_based_win')
            rank_place = strategies.get('rank_based_place')
            
            html += f"""
            <div class="condition-card">
                <h4>{condition_value}</h4>
                <div class="condition-stats">
                    <span class="stat-label">レース数:</span>
                    <span class="stat-value">{best_result.total_races}</span>
                </div>
            """
            
            if rank_win:
                roi_class = 'roi-positive' if rank_win.roi >= 100 else 'roi-negative'
                html += f"""
                <div class="condition-stats">
                    <span class="stat-label">単勝ROI:</span>
                    <span class="stat-value {roi_class}">{rank_win.roi:.1f}%</span>
                </div>
                """
            
            if rank_place:
                roi_class = 'roi-positive' if rank_place.roi >= 100 else 'roi-negative'
                html += f"""
                <div class="condition-stats">
                    <span class="stat-label">複勝ROI:</span>
                    <span class="stat-value {roi_class}">{rank_place.roi:.1f}%</span>
                </div>
                """
            
            html += f"""
                <div class="condition-stats">
                    <span class="stat-label">最高ROI:</span>
                    <span class="stat-value roi-positive">{best_result.roi:.1f}%</span>
                </div>
                <div class="condition-stats">
                    <span class="stat-label" style="font-size:0.8em;">({best_name})</span>
                </div>
            </div>
            """
        
        html += """
            </div>
        </section>
        """
        
        return html


