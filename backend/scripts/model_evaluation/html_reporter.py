    def _get_javascript(self) -> str:
        """JavaScriptコードを取得"""
        return """
        // スムーズスクロール
        document.querySelectorAll('a[href^="#"]').forEach(anchor => {
            anchor.addEventListener('click', function (e) {
                e.preventDefault();
                const target = document.querySelector(this.getAttribute('href'));
                if (target) {
                    target.scrollIntoView({
                        behavior: 'smooth',
                        block: 'start'
                    });
                }
            });
        });
        
        // テーブル行のハイライト
        document.querySelectorAll('table tbody tr').forEach(row => {
            row.addEventListener('mouseenter', function() {
                this.style.transform = 'scale(1.01)';
                this.style.transition = 'transform 0.2s';
            });
            row.addEventListener('mouseleave', function() {
                this.style.transform = 'scale(1)';
            });
        });
        """
    
    def _build_conditional_toc(
        self,
        venue_results: Optional[Dict],
        grade_results: Optional[Dict],
        track_results: Optional[Dict],
        distance_results: Optional[Dict],
        condition_results: Optional[Dict]
    ) -> str:
        """条件別分析の目次を構築"""
        toc_items = []
        section_num = 4
        
        if venue_results:
            toc_items.append(f'<li><a href="#venue">{section_num}. 競馬場別分析</a></li>')
            section_num += 1
        
        if grade_results:
            toc_items.append(f'<li><a href="#grade">{section_num}. グレード別分析</a></li>')
            section_num += 1
        
        if track_results:
            toc_items.append(f'<li><a href="#track-type">{section_num}. トラック別分析</a></li>')
            section_num += 1
        
        if distance_results:
            toc_items.append(f'<li><a href="#distance">{section_num}. 距離別分析</a></li>')
            section_num += 1
        
        if condition_results:
            toc_items.append(f'<li><a href="#condition">{section_num}. 馬場状態別分析</a></li>')
            section_num += 1
        
        return '\n'.join(toc_items)
    
    def _build_overview_section(self, results: Dict[str, StrategyResult]) -> str:
        """総合評価サマリーセクションを構築"""
        # 最高ROIの戦略を見つける
        best_strategy = max(results.items(), key=lambda x: x[1].roi)
        best_name, best_result = best_strategy
        
        # 予想順位ベースの結果
        rank_win = results.get('rank_based_win')
        rank_place = results.get('rank_based_place')
        
        html = f"""
        <section id="overview" class="section">
            <h2>1. 総合評価サマリー</h2>
            
            <div class="alert alert-success">
                <strong>🏆 最高ROI戦略:</strong> {best_name}<br>
                <strong>ROI:</strong> {best_result.roi:.2f}% | 
                <strong>的中率:</strong> {best_result.accuracy:.2f}% | 
                <strong>収支:</strong> {best_result.profit:+,}円
            </div>
            
            <h3>主要指標</h3>
            <div class="metrics-grid">
                <div class="metric-card">
                    <div class="label">評価レース数</div>
                    <div class="value">{best_result.total_races}</div>
                    <div class="unit">レース</div>
                </div>
                <div class="metric-card">
                    <div class="label">評価戦略数</div>
                    <div class="value">{len(results)}</div>
                    <div class="unit">パターン</div>
                </div>
        """
        
        if rank_win:
            roi_class = 'positive' if rank_win.roi > 100 else 'negative'
            html += f"""
                <div class="metric-card {roi_class}">
                    <div class="label">単勝ROI（順位ベース）</div>
                    <div class="value">{rank_win.roi:.1f}</div>
                    <div class="unit">%</div>
                </div>
            """
        
        if rank_place:
            roi_class = 'positive' if rank_place.roi > 100 else 'negative'
            html += f"""
                <div class="metric-card {roi_class}">
                    <div class="label">複勝ROI（順位ベース）</div>
                    <div class="value">{rank_place.roi:.1f}</div>
                    <div class="unit">%</div>
                </div>
            """
        
        html += """
            </div>
        </section>
        """
        
        return html
    
