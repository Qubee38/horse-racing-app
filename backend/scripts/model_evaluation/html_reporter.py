    from .data_loader import DataLoader
    from .evaluator import Evaluator
    from .analyzer import ConditionalAnalyzer
    
    # 設定初期化
    config = EvaluationConfig()
    config.ensure_directories()
    
    # DataLoader初期化
    loader = DataLoader(config)
    
    # テスト用レースID
    test_race_ids = ["202506040901", "202506040902", "202506040903"]
    
    # データ準備
    print("\n=== Preparing Data ===")
    valid_race_ids = loader.prepare_evaluation_data(test_race_ids)
    
    # データ読み込み
    print("\n=== Loading Data ===")
    race_data_list = loader.get_all_race_data(valid_race_ids)
    print(f"Loaded {len(race_data_list)} races")
    
    # Evaluator初期化
    evaluator = Evaluator(config)
    
    # 全戦略で評価
    print("\n=== Evaluating Strategies ===")
    results = evaluator.evaluate_all_strategies(race_data_list)
    
    # 条件別分析
    print("\n=== Conditional Analysis ===")
    analyzer = ConditionalAnalyzer(config, evaluator)
    venue_results = analyzer.analyze_by_venue(race_data_list)
    grade_results = analyzer.analyze_by_grade(race_data_list)
    
    # HTMLReporter初期化
    html_reporter = HTMLReporter(config)
    
    # HTMLレポート生成
    print("\n=== Generating HTML Report ===")
    html_path = html_reporter.generate_html_report(
        results,
        venue_results=venue_results,
        grade_results=grade_results
    )
    
    print(f"\nHTML report generated: {html_path}")
    print(f"Open with: open {html_path}")